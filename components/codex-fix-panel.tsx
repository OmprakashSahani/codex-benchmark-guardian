import type { AnalysisResponse } from "@/lib/types";
import { ArtifactViewer, type Artifact } from "./artifact-viewer";

function ContractSection({ title, values, code = false }: { title: string; values: string[]; code?: boolean }) {
  return <section className="contract-section"><h4>{title}</h4><ul>{values.map((value) => <li key={value}>{code ? <code>{value}</code> : value}</li>)}</ul></section>;
}

export function CodexFixPanel({ result }: { result: AnalysisResponse }) {
  const contract = result.repair_contract;
  const repairRequired = contract.repair_required;
  const artifact: Artifact = {
    key: "codex_repair_goal",
    title: "Codex repair goal",
    description: "Conditional goal generated by the canonical Python Repair Contract.",
    filename: "codex_repair_goal.md",
    mime: "text/markdown;charset=utf-8",
    language: "markdown",
    content: result.codex_repair_goal,
  };

  return <section aria-labelledby="codex-fix-title" className="codex-fix-panel">
    <div className="detail-heading"><div><span className="eyebrow">Canonical Codex handoff</span><h3 id="codex-fix-title">{repairRequired ? "Repair required" : "Verification only"}</h3><p>{!repairRequired && <strong>No code repair required. </strong>}{contract.repair_objective}</p></div></div>
    <div className={`contract-state ${repairRequired ? "contract-state-required" : "contract-state-verify"}`}><strong>{repairRequired ? "Repair required" : "Verification only"}</strong><span>{contract.readiness_label} · {contract.readiness_score}/100</span></div>
    <div className="contract-grid">
      <ContractSection title="Allowed actions" values={contract.allowed_actions} />
      <ContractSection title="Forbidden actions" values={contract.forbidden_actions} />
      <ContractSection title="Required validation commands" values={contract.required_validation_commands} code />
      <ContractSection title="Completion criteria" values={contract.completion_criteria} />
      <ContractSection title="Stop-and-report conditions" values={contract.stop_conditions} />
    </div>
    <ArtifactViewer artifact={artifact} copyLabel="Copy for Codex" downloadLabel="Download goal" />
  </section>;
}
